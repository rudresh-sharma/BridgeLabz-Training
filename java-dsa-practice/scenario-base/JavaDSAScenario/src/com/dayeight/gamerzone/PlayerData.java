package com.dayeight.gamerzone;

public class PlayerData {

	private String name;
	private int score;
	
	public PlayerData(String name, int score) {
		super();
		this.name = name;
		this.score = score;
	}
	
	
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public int getScore() {
		return score;
	}
	public void setScore(int score) {
		this.score = score;
	}
	
	
	
	
	
	
}
